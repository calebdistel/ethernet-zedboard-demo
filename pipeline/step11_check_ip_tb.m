%% setup output directory
here = fileparts(mfilename('fullpath'));
outDir = fullfile(here, '..', 'results', 'vivado');
simDir = fullfile(outDir, 'ip_tb');

%% Load IP testbench stream (one line per accepted beat: TDATA TLAST)
ip = readmatrix(fullfile(simDir, 'ip_stream.txt'));
ipData = ip(:, 1);
ipLast = ip(:, 2);
n = numel(ipData);
writetable(table((0:n-1)', ipData, ipLast, 'VariableNames', {'Beat', 'TDATA', 'TLAST'}), fullfile(outDir, 'ip_stream.csv'));

%% Compare against the valid samples from the cosim (step 7)
cosim = readtable(fullfile(here, '..', 'results', 'simulink', 'cosim_raw.csv'));
ref = cosim.MagData(cosim.MagValid == 1);

dataErrors = nnz(ipData ~= ref(1:n));
lastBeats = find(ipLast)';                 % 1-based beat numbers
expectedLast = 1024:1024:n;

fprintf('IP beats: %d, data mismatches vs cosim: %d\n', n, dataErrors);
fprintf('TLAST at beats %s, expected %s\n', mat2str(lastBeats), mat2str(expectedLast));
if dataErrors == 0 && isequal(lastBeats, expectedLast)
    fprintf('IP core testbench PASSED\n');
else
    fprintf('IP core testbench FAILED\n');
end

%% First IP frame in natural bin order (same as step 7)
k = (0:NFFT-1)';
ipNatural = zeros(NFFT, 1);
ipNatural(bins + 1) = ipData(1:NFFT);
writetable(table(k, ipNatural, 'VariableNames', {'Bin', 'Magnitude'}), fullfile(outDir, 'ip_frame.csv'));

%% Virtual PL for the emulated board (Vitis ZED_EMULATION build)
% Consecutive IP frames in stream order, exactly what the S2MM DMA writes to
% DDR when the chain free-runs between captures.
nGolden = floor(n / NFFT);
golden = uint32(mod(ipData(1:nGolden*NFFT), 2^32));
fid = fopen(fullfile(here, 'sw', 'src', 'golden_frame.h'), 'w');
fprintf(fid, '/* AUTO-GENERATED by pipeline/step11_check_ip_tb.m - do not edit.\n');
fprintf(fid, ' * %d consecutive 1024-beat frames of the SignalCha_ip AXI4-Stream output\n', nGolden);
fprintf(fid, ' * (TDATA, sfix27_En14 raw, stream order) from the IP core RTL simulation\n');
fprintf(fid, ' * (step 10): what the S2MM DMA writes to DDR for successive captures. */\n');
fprintf(fid, '#ifndef GOLDEN_FRAME_H\n#define GOLDEN_FRAME_H\n\n');
fprintf(fid, '#define GOLDEN_FRAMES %d\n\n', nGolden);
fprintf(fid, 'static const u32 GoldenFrames[GOLDEN_FRAMES][%d] = {\n', NFFT);
for f = 1:nGolden
    fprintf(fid, '    {\n');
    g = golden((f-1)*NFFT + (1:NFFT));
    for i = 1:8:NFFT
        fprintf(fid, '        %s,\n', strjoin(compose('0x%08X', g(i:i+7)), ', '));
    end
    fprintf(fid, '    },\n');
end
fprintf(fid, '};\n\n#endif\n');
fclose(fid);
fprintf('Wrote golden_frame.h (%d frames)\n', nGolden);

%% Plot against all previous outputs
slDir = fullfile(here, '..', 'results', 'simulink');
ref   = readtable(fullfile(slDir, 'reference_frame.csv'));
sl    = readtable(fullfile(slDir, 'simulink_frame.csv'));
hdl   = readtable(fullfile(slDir, 'cosim_frame.csv'));

plotSpectrumComparison(ref.Bin, {ref.Magnitude, sl.Magnitude, hdl.Magnitude, ipNatural}, ...
    {'Reference', 'Simulink', 'HDL cosim', 'IP core'}, ...
    'Reference vs. Simulink vs. HDL Cosimulation vs. IP Core', ...
    fullfile(outDir, 'reference_vs_simulink_vs_cosim_vs_ip.png'));
